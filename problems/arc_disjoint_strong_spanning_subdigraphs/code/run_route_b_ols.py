def _h1_passes(cl1: dict[str, Any]) -> bool:
    """Hypothesis (1) is satisfied iff both parts have status SAT or NA."""
    return (
        cl1.get("v1_sad_status") in ("SAT", "NA")
        and cl1.get("v2_sad_status") in ("SAT", "NA")
    )


def _h2_passes(cl1: dict[str, Any]) -> bool:
    return (
        cl1.get("bridges_plus_R", 0) > 0
        and cl1.get("bridges_plus_B", 0) > 0
        and cl1.get("bridges_minus_R", 0) > 0
        and cl1.get("bridges_minus_B", 0) > 0
    )


def aggregate_cl1(log: OlsLog) -> dict[str, Any]:
    cands = [c for c in log.candidates if c.get("sat_status") == "SAT"]
    if not cands:
        return {"n_candidates": 0}

    n = len(cands)
    h1_pass = sum(1 for c in cands if _h1_passes(c["cl1"]))
    h2_pass = sum(1 for c in cands if _h2_passes(c["cl1"]))
    both_pass = sum(
        1 for c in cands if _h1_passes(c["cl1"]) and _h2_passes(c["cl1"])
    )

    # Per-construction breakdown.
    per_constr: dict[str, dict[str, Any]] = {}
    bk: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for c in cands:
        bk[c["construction"]].append(c)
    for k, b in bk.items():
        m = len(b)
        h1 = sum(1 for c in b if _h1_passes(c["cl1"]))
        h2 = sum(1 for c in b if _h2_passes(c["cl1"]))
        per_constr[k] = {
            "n": m,
            "h1_pass": h1,
            "h1_frac": h1 / m,
            "h2_pass": h2,
            "h2_frac": h2 / m,
        }

    # Per-component-shape breakdown for Construction A (the meaningful
    # Route B regime). The anchor is the *first* component, which is
    # what _choose_partition uses as V_1.
    per_anchor: dict[str, dict[str, Any]] = {}
    bk_anchor: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for c in cands:
        if c["construction"] != "A_round":
            continue
        if not c["component_shapes"]:
            continue
        anchor = c["component_shapes"][0]
        bk_anchor[anchor].append(c)
    for k, b in bk_anchor.items():
        m = len(b)
        h1 = sum(1 for c in b if _h1_passes(c["cl1"]))
        h2 = sum(1 for c in b if _h2_passes(c["cl1"]))
        per_anchor[k] = {
            "n": m,
            "h1_pass": h1,
            "h1_frac": h1 / m,
            "h2_pass": h2,
            "h2_frac": h2 / m,
        }

    # H1-failure breakdown: which part fails, and why? Useful for the
    # diagnostic exception-family discussion.
    h1_fail_details: dict[str, int] = defaultdict(int)
    for c in cands:
        if _h1_passes(c["cl1"]):
            continue
        v1s = c["cl1"]["v1_sad_status"]
        v2s = c["cl1"]["v2_sad_status"]
        h1_fail_details[f"V1={v1s}, V2={v2s}"] += 1

    return {
        "n_candidates": n,
        "hypothesis_1_pass": h1_pass,
        "hypothesis_1_frac": h1_pass / n,
        "hypothesis_2_pass": h2_pass,
        "hypothesis_2_frac": h2_pass / n,
        "both_pass": both_pass,
        "both_frac": both_pass / n,
        "per_construction": per_constr,
        "per_anchor_shape_A": per_anchor,
        "h1_failure_breakdown": dict(h1_fail_details),
    }


def aggregate_canonical(log: OlsLog) -> dict[str, Any]:
    cands = [c for c in log.candidates if c.get("sat_status") == "SAT"]
    keys: dict[str, list[str]] = defaultdict(list)
    for c in cands:
        keys[c["canonical_hash"]].append(c["name"])
    classes = sorted(keys.values(), key=len, reverse=True)
    size_dist = Counter(len(c) for c in classes)
    return {
        "n_labeled_distinct": len(cands),
        "n_canonical_distinct": len(keys),
        "largest_iso_class_size": len(classes[0]) if classes else 0,
        "iso_class_size_distribution": {
            str(k): v for k, v in sorted(size_dist.items())
        },
    }


