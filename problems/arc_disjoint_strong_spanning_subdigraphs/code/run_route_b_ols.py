def _instance_to_entry(
    inst: OlsInstance,
    witness: tuple[list[tuple[int, int, int]], list[tuple[int, int, int]]],
    cross: Any,
    cl1: CL1Record,
    canonical: str,
) -> dict[str, Any]:
    red, blue = witness
    return {
        "name": inst.name,
        "n": inst.n,
        "m": len(inst.arcs),
        "construction": inst.construction,
        "components": [list(c) for c in inst.components],
        "component_shapes": list(inst.component_shapes),
        "arcs": [list(a) for a in inst.arcs],
        "ilp_status": cross.ilp.get("status"),
        "sat_status": cross.sat.get("status"),
        "ilp_time": cross.ilp.get("time_s"),
        "sat_time": cross.sat.get("time_s"),
        "witness_red": [[u, v, k] for (u, v, k) in red],
        "witness_blue": [[u, v, k] for (u, v, k) in blue],
        "canonical_hash": canonical,
        "cl1": asdict(cl1),
    }


def _unsat_entry(inst: OlsInstance, cross: Any) -> dict[str, Any]:
    return {
        "name": inst.name,
        "n": inst.n,
        "m": len(inst.arcs),
        "construction": inst.construction,
        "components": [list(c) for c in inst.components],
        "component_shapes": list(inst.component_shapes),
        "arcs": [list(a) for a in inst.arcs],
        "ilp_status": cross.ilp.get("status"),
        "sat_status": cross.sat.get("status"),
    }


def stream_candidates(
    cap_A: int,
    cap_B: int,
    cap_C: int,
    seed: int,
) -> list[OlsInstance]:
    """Build a deterministic shuffled stream from A, B, C generators."""
    out: list[OlsInstance] = []
    seen_arcs: set[tuple[tuple[int, int], ...]] = set()
    for inst in enumerate_construction_A(seed=seed, cap_per_p=cap_A // 4 + 5):
        key = tuple(sorted(inst.arcs))
        if key in seen_arcs:
            continue
        seen_arcs.add(key)
        out.append(inst)
        if sum(1 for x in out if x.construction == "A_round") >= cap_A:
            break
    nB = 0
    for inst in enumerate_construction_B(seed=seed + 1, cap=cap_B):
        key = tuple(sorted(inst.arcs))
        if key in seen_arcs:
            continue
        seen_arcs.add(key)
        out.append(inst)
        nB += 1
        if nB >= cap_B:
            break
    nC = 0
    for inst in enumerate_construction_C(seed=seed + 2, cap_attempts=cap_C * 80):
        key = tuple(sorted(inst.arcs))
        if key in seen_arcs:
            continue
        seen_arcs.add(key)
        out.append(inst)
        nC += 1
        if nC >= cap_C:
            break
    # Don't shuffle: process A first (most structured), then B, then C.
    return out


def run_sweep(
    candidates: list[OlsInstance],
    instance_time_s: float,
    log: OlsLog,
) -> None:
    stats = OlsStats()
    t0 = time.time()
    by_constr: dict[str, int] = defaultdict(int)
    by_constr_k3: dict[str, int] = defaultdict(int)
    by_constr_sat: dict[str, int] = defaultdict(int)

    for inst in candidates:
        stats.streamed += 1
        by_constr[inst.construction] += 1

        # 1. Independent OLS check.
        D = inst.build()
        if not is_out_locally_semicomplete(D):
            # The generator should never produce non-OLS for A_round / B_tail.
            log.notes.append(
                f"NON-OLS generated (BUG?): {inst.name}"
            )
            continue
        stats.ols_confirmed += 1

        # 2. Strongly connected?
        if not D.is_strongly_connected():
            continue
        stats.strong += 1

        # 3. Arc connectivity gate: exactly 3.
        lam = D.arc_connectivity()
        if lam < 3:
            stats.kappa_lower += 1
            continue
        if lam > 3:
            stats.kappa_higher += 1
            continue
        stats.kappa3_pass += 1
        by_constr_k3[inst.construction] += 1

        # 4. Cross-check ILP + SAT.
        cross = cross_check(D, inst.name, time_limit_s=instance_time_s)
        if not cross.agree:
            stats.disagreements += 1
            log.notes.append(
                f"FATAL: cross-check disagree on {inst.name}: "
                f"ILP={cross.ilp.get('status')} SAT={cross.sat.get('status')}"
            )
            print(f"  *** FATAL DISAGREE: {inst.name}", flush=True)
            continue

        status = cross.ilp.get("status")
        if status == "UNSAT":
            stats.verified_unsat += 1
            print(
                f"  *** UNSAT 3-arc-strong OLS candidate ***  name={inst.name}  "
                f"n={inst.n}  m={len(inst.arcs)}  construction={inst.construction}",
                flush=True,
            )
            log.notes.append(
                f"COUNTEREXAMPLE candidate (Route B): {inst.name} -- "
                f"run team/01 checklist; write team/12_candidate_counterexample.md"
            )
            log.counterexamples.append(_unsat_entry(inst, cross))
            # Per spec hard rule: stop on lambda=3 UNSAT.
            print(
                "  *** STOPPING SWEEP: lambda=3 OLS UNSAT triggers "
                "team/01 ten-item checklist. ***",
                flush=True,
            )
            break

        if status != "SAT":
            log.notes.append(
                f"UNKNOWN status on {inst.name}: ILP={status} "
                f"SAT={cross.sat.get('status')}"
            )
            continue

        stats.verified_sat += 1
        by_constr_sat[inst.construction] += 1
        witness = cross.sat.get("witness")
        if witness is None:
            log.notes.append(f"no SAT witness recovered for {inst.name}")
            continue

        cl1 = analyse_cl1(inst, D, witness, instance_time_s=instance_time_s)
        canonical = canonical_key(D)
        entry = _instance_to_entry(inst, witness, cross, cl1, canonical)
        log.candidates.append(entry)

        if stats.streamed % 50 == 0:
            print(
                f"  [OLS] streamed={stats.streamed} ols={stats.ols_confirmed} "
                f"k3={stats.kappa3_pass} sat={stats.verified_sat} "
                f"unsat={stats.verified_unsat} elapsed={time.time() - t0:.0f}s",
                flush=True,
            )

    stats.elapsed_s = time.time() - t0
    stats.by_construction = dict(by_constr)
    stats.by_construction_k3 = dict(by_constr_k3)
    stats.by_construction_sat = dict(by_constr_sat)
    log.stats = asdict(stats)


