@dataclass
class CL1Record:
    """Per-instance CL1 hypothesis-test record.

    Hypothesis (1) is the intrinsic SAD-decomposability of each part
    D[V_1] and D[V_2]. We test it by running `verify_sat` on each
    induced subdigraph (treating it as a stand-alone digraph). A part
    of size 1 is vacuously "SAD-decomposable" (it has no arcs to
    decompose).

    Hypothesis (2) is the bridge 2-coloring with each (direction,
    colour) class non-empty. We read it off the original witness on D
    directly.
    """

    # Partition V = V_1 \cup V_2 chosen (V_1 = anchor component for A;
    # for B/C the partition is heuristic — first half / second half by
    # vertex index).
    v1_size: int = 0
    v2_size: int = 0
    v1: list[int] = field(default_factory=list)
    v2: list[int] = field(default_factory=list)

    # Hypothesis (1): intrinsic SAD-decomposability of D[V_i].
    v1_lambda: int = 0
    v2_lambda: int = 0
    v1_sad_status: str = "?"  # SAT, UNSAT, UNKNOWN, NA (trivial part)
    v2_sad_status: str = "?"

    # Number of arcs of each colour on each inner part (as a *witness*
    # restriction sanity check; if the witness restricts to a SAD, it
    # would be the cleanest proof).
    inner1_red_n_arcs: int = 0
    inner1_blue_n_arcs: int = 0
    inner2_red_n_arcs: int = 0
    inner2_blue_n_arcs: int = 0
    inner1_red_strong: bool = False
    inner1_blue_strong: bool = False
    inner2_red_strong: bool = False
    inner2_blue_strong: bool = False

    # Hypothesis (2): bridge 2-coloring with each (direction, colour)
    # non-empty.
    bridges_plus_total: int = 0  # V_1 -> V_2
    bridges_minus_total: int = 0  # V_2 -> V_1
    bridges_plus_R: int = 0
    bridges_plus_B: int = 0
    bridges_minus_R: int = 0
    bridges_minus_B: int = 0

    @property
    def hypothesis_1_holds(self) -> bool:
        """Both parts admit a SAD (intrinsic test)."""
        ok = []
        for st in (self.v1_sad_status, self.v2_sad_status):
            if st in ("SAT", "NA"):
                ok.append(True)
            else:
                ok.append(False)
        return all(ok)

    @property
    def hypothesis_2_holds(self) -> bool:
        """Each (direction, colour) class is non-empty."""
        return (
            self.bridges_plus_R > 0 and self.bridges_plus_B > 0
            and self.bridges_minus_R > 0 and self.bridges_minus_B > 0
        )


def _keyed_arcs(arcs: list[tuple[int, int]]) -> list[tuple[int, int, int]]:
    ctr: Counter = Counter()
    out: list[tuple[int, int, int]] = []
    for (u, v) in arcs:
        k = ctr[(u, v)]
        out.append((u, v, k))
        ctr[(u, v)] += 1
    return out


def _choose_partition(inst: OlsInstance) -> tuple[list[int], list[int]]:
    """Choose CL1 partition V = V_1 \cup V_2.

    Construction A: V_1 = first component C_1; V_2 = V \ V_1.
    Constructions B, C: heuristic — V_1 = first half of vertices by
    index, V_2 = second half (both sizes >= 2).
    """
    if inst.construction == "A_round" and inst.components:
        v1 = sorted(inst.components[0])
        v2 = sorted(v for v in range(inst.n) if v not in set(v1))
        return v1, v2
    half = inst.n // 2
    v1 = list(range(half))
    v2 = list(range(half, inst.n))
    return v1, v2


def _induced_subdigraph(D: Digraph, vertex_set: list[int]) -> Digraph:
    """Build the induced subdigraph D[vertex_set] preserving parallel arcs."""
    S = set(vertex_set)
    arcs = []
    for u, v, _k in D.arcs():
        if u in S and v in S:
            arcs.append((u, v))
    return Digraph.from_arcs(sorted(S), arcs)


def analyse_cl1(
    inst: OlsInstance,
    D: Digraph,
    witness: tuple[list[tuple[int, int, int]], list[tuple[int, int, int]]],
    instance_time_s: float = 8.0,
) -> CL1Record:
    red_arcs, blue_arcs = witness
    red_set = set(red_arcs)
    v1_list, v2_list = _choose_partition(inst)
    v1_set = set(v1_list)
    v2_set = set(v2_list)
    rec = CL1Record(
        v1_size=len(v1_list),
        v2_size=len(v2_list),
        v1=list(v1_list),
        v2=list(v2_list),
    )

    # Restrict witness arcs to inner V_1 and V_2; count bridges.
    inner1_red: list[tuple[int, int, int]] = []
    inner1_blue: list[tuple[int, int, int]] = []
    inner2_red: list[tuple[int, int, int]] = []
    inner2_blue: list[tuple[int, int, int]] = []
    for ke in red_arcs + blue_arcs:
        u, v, _k = ke
        u_in_1 = u in v1_set
        v_in_1 = v in v1_set
        is_red = ke in red_set
        if u_in_1 and v_in_1:
            if is_red:
                inner1_red.append(ke)
            else:
                inner1_blue.append(ke)
        elif (not u_in_1) and (not v_in_1):
            if is_red:
                inner2_red.append(ke)
            else:
                inner2_blue.append(ke)
        elif u_in_1 and not v_in_1:
            rec.bridges_plus_total += 1
            if is_red:
                rec.bridges_plus_R += 1
            else:
                rec.bridges_plus_B += 1
        else:
            rec.bridges_minus_total += 1
            if is_red:
                rec.bridges_minus_R += 1
            else:
                rec.bridges_minus_B += 1

    rec.inner1_red_n_arcs = len(inner1_red)
    rec.inner1_blue_n_arcs = len(inner1_blue)
    rec.inner2_red_n_arcs = len(inner2_red)
    rec.inner2_blue_n_arcs = len(inner2_blue)

    # Strong-connectivity of restricted colour classes on each part.
    if v1_list:
        R1 = Digraph.from_arcs(v1_list, [(u, v) for (u, v, _k) in inner1_red])
        B1 = Digraph.from_arcs(v1_list, [(u, v) for (u, v, _k) in inner1_blue])
        rec.inner1_red_strong = R1.is_strongly_connected() if len(v1_list) >= 2 else True
        rec.inner1_blue_strong = B1.is_strongly_connected() if len(v1_list) >= 2 else True
    if v2_list:
        R2 = Digraph.from_arcs(v2_list, [(u, v) for (u, v, _k) in inner2_red])
        B2 = Digraph.from_arcs(v2_list, [(u, v) for (u, v, _k) in inner2_blue])
        rec.inner2_red_strong = R2.is_strongly_connected() if len(v2_list) >= 2 else True
        rec.inner2_blue_strong = B2.is_strongly_connected() if len(v2_list) >= 2 else True

    # Hypothesis (1), intrinsic: run verify_sat on D[V_1] and D[V_2].
    # Trivial parts (n <= 1) are SAD by convention.
    for vlist, status_attr, lam_attr in (
        (v1_list, "v1_sad_status", "v1_lambda"),
        (v2_list, "v2_sad_status", "v2_lambda"),
    ):
        if len(vlist) <= 1:
            setattr(rec, status_attr, "NA")
            setattr(rec, lam_attr, 0)
            continue
        Dpart = _induced_subdigraph(D, vlist)
        if not Dpart.is_strongly_connected():
            setattr(rec, status_attr, "UNSAT")  # not strong => no SAD
            setattr(rec, lam_attr, 0)
            continue
        lam = Dpart.arc_connectivity()
        setattr(rec, lam_attr, lam)
        if lam < 2:
            # 1-arc-strong digraphs cannot have a SAD: each colour class
            # would need to be strong, requiring lambda >= 2 in the
            # original. Mark UNSAT without running the solver.
            setattr(rec, status_attr, "UNSAT")
            continue
        res = verify_sat(Dpart, time_limit_s=instance_time_s)
        setattr(rec, status_attr, res.get("status", "UNKNOWN"))

    return rec


