@dataclass
class OlsStats:
    streamed: int = 0
    ols_confirmed: int = 0
    strong: int = 0
    kappa3_pass: int = 0
    kappa_higher: int = 0
    kappa_lower: int = 0
    verified_sat: int = 0
    verified_unsat: int = 0
    disagreements: int = 0
    elapsed_s: float = 0.0

    by_construction: dict[str, int] = field(default_factory=dict)
    by_construction_k3: dict[str, int] = field(default_factory=dict)
    by_construction_sat: dict[str, int] = field(default_factory=dict)


@dataclass
class OlsLog:
    started_at: str
    config: dict[str, Any] = field(default_factory=dict)
    stats: dict[str, Any] = field(default_factory=dict)
    candidates: list[dict[str, Any]] = field(default_factory=list)
    canonical_summary: dict[str, Any] = field(default_factory=dict)
    cl1_summary: dict[str, Any] = field(default_factory=dict)
    counterexamples: list[dict[str, Any]] = field(default_factory=list)
    finished_at: str | None = None
    elapsed_s: float | None = None
    notes: list[str] = field(default_factory=list)


