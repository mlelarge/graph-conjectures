"""Route-B OLS empirical sweep (companion to `team/15_v6_ols_empirical.md`).

This driver mirrors `run_phase4_vehicle6.py` but operates on OLS digraphs
generated by `code/generators/ols.py`. For each candidate we:

  1. confirm OLS via the independent predicate
     `is_out_locally_semicomplete(D)`;
  2. confirm arc-connectivity is exactly 3 (the target regime);
  3. cross-check ILP + SAT, expect SAT (Route B theorem);
  4. log the SAT witness;
  5. test CL1's two hypotheses on the witness:
        (1) D[V_1] and D[V_2] admit a SAD (we restrict the witness to
            each part and check strong connectivity of each colour);
        (2) bridges from V_1 to V_2 and V_2 to V_1 admit a 2-coloring
            with each (direction, colour) class non-empty (just count
            bridges per colour per direction in the witness);
  6. compute the canonical hash.

Hard rules enforced:
  - witness logging mandatory for every SAT instance;
  - hit-rate floor (>= 5 % at lambda = 3 gate);
  - independent OLS verification (Construction A's construction does
    not bypass `is_out_locally_semicomplete`);
  - stop-on-lambda=3 UNSAT (write a counterexample notice).

Outputs:
  - JSON log at code/logs/route_b_ols_<timestamp>.json with full
    witnesses, canonical hashes, per-instance CL1 records.
"""

