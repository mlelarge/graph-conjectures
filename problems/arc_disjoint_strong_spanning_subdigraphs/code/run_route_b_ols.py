def main() -> int:
    p = argparse.ArgumentParser(description="Route-B OLS empirical sweep")
    p.add_argument("--cap-A", type=int, default=600, help="cap on Construction A")
    p.add_argument("--cap-B", type=int, default=40, help="cap on Construction B")
    p.add_argument("--cap-C", type=int, default=120, help="cap on Construction C")
    p.add_argument("--instance-time-s", type=float, default=10.0)
    p.add_argument("--logs-dir", default=str(HERE / "logs"))
    p.add_argument("--seed", type=int, default=20260516)
    args = p.parse_args()

    timestamp = time.strftime("%Y%m%d_%H%M%S")
    logs_dir = Path(args.logs_dir)
    logs_dir.mkdir(parents=True, exist_ok=True)
    log_path = logs_dir / f"route_b_ols_{timestamp}.json"

    print("=" * 72, flush=True)
    print("Route B — 3-arc-strong OLS empirical sweep", flush=True)
    print("=" * 72, flush=True)

    print(f"Semicomplete shape catalog: {len(SEMICOMPLETE_SHAPES)} entries", flush=True)
    for sh in SEMICOMPLETE_SHAPES:
        print(f"  shape={sh.name:6s} n={sh.n}", flush=True)
    print(flush=True)

    log = OlsLog(
        started_at=time.strftime("%Y-%m-%d %H:%M:%S"),
        config={
            "cap_A": args.cap_A,
            "cap_B": args.cap_B,
            "cap_C": args.cap_C,
            "instance_time_s": args.instance_time_s,
            "seed": args.seed,
        },
    )

    candidates = stream_candidates(args.cap_A, args.cap_B, args.cap_C, args.seed)
    print(f"Streamed candidate list: {len(candidates)} instances", flush=True)
    constr_count = Counter(c.construction for c in candidates)
    for k, v in constr_count.items():
        print(f"  {k}: {v}", flush=True)
    print(flush=True)

    t0 = time.time()
    run_sweep(
        candidates=candidates,
        instance_time_s=args.instance_time_s,
        log=log,
    )

    log.cl1_summary = aggregate_cl1(log)
    log.canonical_summary = aggregate_canonical(log)
    log.finished_at = time.strftime("%Y-%m-%d %H:%M:%S")
    log.elapsed_s = time.time() - t0

    # ---- stdout report -----------------------------------------------------
    print("=" * 72, flush=True)
    print("Sweep complete.", flush=True)
    s = log.stats
    print(
        f"  streamed={s['streamed']} ols={s['ols_confirmed']} strong={s['strong']} "
        f"kappa=3 exactly={s['kappa3_pass']} kappa>3 (rej)={s['kappa_higher']} "
        f"kappa<3={s['kappa_lower']}",
        flush=True,
    )
    print(
        f"  verified_sat={s['verified_sat']} verified_unsat={s['verified_unsat']} "
        f"disagreements={s['disagreements']} elapsed={s['elapsed_s']:.0f}s",
        flush=True,
    )
    hit_rate = s["kappa3_pass"] / max(s["streamed"], 1)
    print(
        f"  hit-rate(lambda=3 | streamed) = {100 * hit_rate:.1f}% "
        f"(floor 5%; {'OK' if hit_rate >= 0.05 else 'BELOW FLOOR'})",
        flush=True,
    )

    cs = log.canonical_summary
    print(
        f"  canonical: {cs['n_labeled_distinct']} labeled-distinct -> "
        f"{cs['n_canonical_distinct']} canonical-distinct  "
        f"(largest iso-class={cs['largest_iso_class_size']})",
        flush=True,
    )

    print(f"\nBy construction:", flush=True)
    bc = s.get("by_construction", {})
    bk = s.get("by_construction_k3", {})
    bs = s.get("by_construction_sat", {})
    for k in sorted(bc.keys()):
        print(
            f"  {k:12s} streamed={bc.get(k, 0):4d}  "
            f"lambda3={bk.get(k, 0):4d}  sat={bs.get(k, 0):4d}",
            flush=True,
        )

    cl1s = log.cl1_summary
    if cl1s.get("n_candidates", 0) > 0:
        print("\n" + "=" * 72, flush=True)
        print("CL1 hypothesis tests (per SAT instance)", flush=True)
        print("=" * 72, flush=True)
        n = cl1s["n_candidates"]
        print(
            f"  Hypothesis (1) — inner SAD on V_1 and V_2 (witness restriction):  "
            f"{100 * cl1s['hypothesis_1_frac']:6.2f}%  "
            f"({cl1s['hypothesis_1_pass']}/{n})",
            flush=True,
        )
        print(
            f"  Hypothesis (2) — both directions bichromatic bridges:           "
            f"{100 * cl1s['hypothesis_2_frac']:6.2f}%  "
            f"({cl1s['hypothesis_2_pass']}/{n})",
            flush=True,
        )
        print(
            f"  Both:                                                          "
            f"{100 * cl1s['both_frac']:6.2f}%  "
            f"({cl1s['both_pass']}/{n})",
            flush=True,
        )

        print("\nBy construction (within SAT instances):", flush=True)
        for k, d in sorted(cl1s["per_construction"].items()):
            print(
                f"  {k:12s} n={d['n']:4d}  "
                f"H1={100*d['h1_frac']:6.2f}%  H2={100*d['h2_frac']:6.2f}%",
                flush=True,
            )

        print("\nConstruction A — by anchor (C_1) shape:", flush=True)
        for k, d in sorted(
            cl1s.get("per_anchor_shape_A", {}).items(),
            key=lambda kv: -kv[1]["n"],
        ):
            print(
                f"  anchor={k:6s} n={d['n']:4d}  "
                f"H1={100*d['h1_frac']:6.2f}%  H2={100*d['h2_frac']:6.2f}%",
                flush=True,
            )

        h1fail = cl1s.get("h1_failure_breakdown", {})
        if h1fail:
            print("\nH1-failure breakdown (V1 status / V2 status):", flush=True)
            for k, v in sorted(h1fail.items(), key=lambda kv: -kv[1]):
                print(f"  {k:40s} count={v}", flush=True)

    if s["verified_unsat"] > 0:
        print("\n" + "=" * 72, flush=True)
        print(
            "WARNING: UNSAT 3-arc-strong OLS candidate(s) found!", flush=True
        )
        print(
            f"   Run team/01 ten-item checklist; canonicalize; "
            f"produce team/12_candidate_counterexample.md.",
            flush=True,
        )
        for ce in log.counterexamples:
            print(f"   - {ce['name']}  n={ce['n']}", flush=True)

    print(f"\nlog: {log_path}", flush=True)
    with log_path.open("w") as f:
        json.dump(asdict(log), f, indent=2, default=str)

    return 0


